#!/usr/bin/env python3
"""Замер расхода токенов этапа по журналам Claude Code

Читает журнал сессии куратора и журналы её субагентов из ~/.claude/projects/<каталог>/ и
считает расход в долларах по ценам API: чтение кэша, запись в кэш, вход и вывод - каждое по
своей цене модели. Цена API - ориентир для подписки, а не её счётчик: как подписка взвешивает
модели, не публикуется.

    python3 tools/usage/usage.py --с 19:25                  # этап с 19:25 сегодня, текущая сессия
    python3 tools/usage/usage.py --с 2026-10-11T19:25 --по 2026-10-11T20:52
    python3 tools/usage/usage.py --с 19:25 --сессия <id>    # сессия не последняя изменённая
    python3 tools/usage/usage.py --с 19:25 --подробно       # строка на каждый субагент

Куратор - сообщения основной сессии внутри окна; субагенты - те, что стартовали внутри окна.
Роль субагента - по типу: stage-executor - исполнитель, stage-reviewer - ревьюер, остальные -
прочие; имена ролей проекта - в РОЛИ ниже. Цены моделей тоже стареют - сверять перед замером.
Последняя строка вывода - готовый хвост строки «Замер» для log.md (docs/stage-cycle.md, раздел 8).
"""
import argparse
import collections
import datetime
import glob
import json
import os
import re
import sys

# $ за 1М токенов: вход, вывод, чтение кэша; запись в кэш - 1,25 входа (5 минут) и 2 входа (1 час)
ЦЕНЫ = {
    "claude-opus-5-5": (4.0, 20.0, 0.20),
    "claude-opus-5": (5.0, 25.0, 0.50),
    "claude-sonnet-5-5": (2.0, 10.0, 0.20),
    "claude-sonnet-5": (2.0, 10.0, 0.20),
    "claude-haiku-5-5": (0.10, 0.50, 0.01),
    "claude-fable-5-1": (10.0, 50.0, 0.25),
}
МОДЕЛЬ_ПО_УМОЛЧАНИЮ = "claude-opus-5-5"
РОЛИ = {"stage-executor": "исполнитель", "stage-reviewer": "ревьюер"}


def каталог_проекта(рабочий_каталог):
    имя = re.sub(r"[^A-Za-z0-9]", "-", os.path.abspath(рабочий_каталог))
    return os.path.join(os.path.expanduser("~/.claude/projects"), имя)


def момент(текст):
    """Локальное время из «ЧЧ:ММ» (сегодня) или ISO-строки - в UTC."""
    if re.fullmatch(r"\d{1,2}:\d{2}", текст):
        часы, минуты = map(int, текст.split(":"))
        локальное = datetime.datetime.now().replace(hour=часы, minute=минуты, second=0, microsecond=0)
    else:
        локальное = datetime.datetime.fromisoformat(текст)
    if локальное.tzinfo is None:
        локальное = локальное.astimezone()
    return локальное.astimezone(datetime.timezone.utc)


def время_записи(запись):
    метка = запись.get("timestamp")
    if not метка:
        return None
    return datetime.datetime.fromisoformat(метка.replace("Z", "+00:00"))


def цена_вызова(модель, расход):
    базовая = модель.split("[")[0]
    вход, вывод, чтение = ЦЕНЫ.get(базовая, ЦЕНЫ[МОДЕЛЬ_ПО_УМОЛЧАНИЮ])
    кэш = расход.get("cache_creation") or {}
    запись_час = кэш.get("ephemeral_1h_input_tokens", 0)
    if кэш:
        запись_5м = кэш.get("ephemeral_5m_input_tokens", 0)
    else:
        запись_5м = расход.get("cache_creation_input_tokens", 0)
    сумма = (расход.get("input_tokens", 0) * вход
             + запись_5м * вход * 1.25
             + запись_час * вход * 2
             + расход.get("cache_read_input_tokens", 0) * чтение
             + расход.get("output_tokens", 0) * вывод)
    контекст = (расход.get("input_tokens", 0) + запись_5м + запись_час
                + расход.get("cache_read_input_tokens", 0))
    return сумма / 1e6, контекст, базовая not in ЦЕНЫ


def разобрать_журнал(путь, начало, конец):
    """Вызовы модели в окне: [(время, $, контекст)], признак неизвестной модели, время первой записи."""
    вызовы = {}
    неизвестная = False
    первая = None
    with open(путь, encoding="utf-8", errors="replace") as файл:
        for строка in файл:
            try:
                запись = json.loads(строка)
            except ValueError:
                continue
            когда = время_записи(запись)
            if когда and первая is None:
                первая = когда
            if запись.get("type") != "assistant" or когда is None:
                continue
            if когда < начало or (конец and когда > конец):
                continue
            сообщение = запись.get("message") or {}
            расход = сообщение.get("usage")
            ид = сообщение.get("id")
            if not расход or not ид or ид in вызовы:
                continue
            сумма, контекст, чужая = цена_вызова(сообщение.get("model") or МОДЕЛЬ_ПО_УМОЛЧАНИЮ, расход)
            неизвестная = неизвестная or чужая
            вызовы[ид] = (когда, сумма, контекст)
    return list(вызовы.values()), неизвестная, первая


def деньги(сумма):
    return f"{сумма:.1f}".replace(".", ",")


def main():
    разбор = argparse.ArgumentParser(description="Замер расхода токенов этапа по журналам Claude Code")
    разбор.add_argument("--с", dest="начало", required=True, help="начало окна: ЧЧ:ММ сегодня или ISO-время")
    разбор.add_argument("--по", dest="конец", help="конец окна (по умолчанию - сейчас)")
    разбор.add_argument("--сессия", help="id сессии куратора (по умолчанию - последний изменённый журнал)")
    разбор.add_argument("--каталог", help="каталог журналов проекта (по умолчанию - по текущему каталогу)")
    разбор.add_argument("--подробно", action="store_true", help="строка на каждый субагент")
    аргументы = разбор.parse_args()

    начало = момент(аргументы.начало)
    конец = момент(аргументы.конец) if аргументы.конец else None
    каталог = аргументы.каталог or каталог_проекта(os.getcwd())
    if аргументы.сессия:
        журнал = os.path.join(каталог, аргументы.сессия + ".jsonl")
    else:
        журналы = glob.glob(os.path.join(каталог, "*.jsonl"))
        журнал = max(журналы, key=os.path.getmtime) if журналы else ""
    if not os.path.exists(журнал):
        sys.exit(f"Нет журнала сессии в {каталог}")
    сессия = os.path.basename(журнал)[:-len(".jsonl")]

    итоги = collections.Counter()
    строки = []
    неизвестная_модель = False
    вызовы, чужая, _ = разобрать_журнал(журнал, начало, конец)
    неизвестная_модель |= чужая
    итоги["куратор"] += sum(в[1] for в in вызовы)
    for путь in sorted(glob.glob(os.path.join(каталог, сессия, "subagents", "*.jsonl"))):
        описание_файла = путь[:-len(".jsonl")] + ".meta.json"
        try:
            with open(описание_файла, encoding="utf-8") as файл:
                мета = json.load(файл)
        except (OSError, ValueError):
            мета = {}
        вызовы, чужая, первая = разобрать_журнал(путь, начало, конец)
        if not вызовы or первая is None or первая < начало:
            continue
        неизвестная_модель |= чужая
        роль = РОЛИ.get(мета.get("agentType"), "прочие")
        сумма = sum(в[1] for в in вызовы)
        итоги[роль] += сумма
        строки.append((первая, роль, мета.get("description", ""), len(вызовы),
                       max(в[2] for в in вызовы), сумма))

    if аргументы.подробно:
        for первая, роль, описание, число, контекст, сумма in sorted(строки):
            print(f"{первая.astimezone():%H:%M}  {роль:12} {описание[:48]:48} вызовов {число:4}  "
                  f"контекст до {контекст // 1000:4}K  ${деньги(сумма)}")
    for роль in ("исполнитель", "ревьюер", "прочие", "куратор"):
        if round(итоги[роль], 1):
            print(f"{роль:12} ${деньги(итоги[роль])}")
    всего = sum(итоги.values())
    print(f"{'итого':12} ${деньги(всего)}")
    if неизвестная_модель:
        print(f"Есть модели вне таблицы цен - посчитаны по {МОДЕЛЬ_ПО_УМОЛЧАНИЮ}")
    части = [f"{сокращение} {деньги(итоги[роль])}" for роль, сокращение in
             (("исполнитель", "исп."), ("ревьюер", "рев."), ("куратор", "куратор"), ("прочие", "прочие"))
             if round(итоги[роль], 1)]
    print(f"Замер: ~${деньги(всего)} по ценам API ({' / '.join(части)})")


if __name__ == "__main__":
    main()
