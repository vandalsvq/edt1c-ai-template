#!/usr/bin/env python3
"""Механические проверки диффа одним проходом

Проверяет то, что глазом пропускается, а EDT и сборка не ловят, и выводит только находки:

- вложенные вызовы и вызовы в заголовке цикла - tools/nested-calls/nested-calls.pl
  (docs/bsl-coding-standards.md, «Вложенные вызовы - всегда в переменную»);
- выровненные по «=» соседние строки, где результат строки идёт аргументом в следующую (там же,
  последний абзац): шаги не выравниваются;
- тире кроме дефиса-минуса в добавленных строках (там же, «Тире»);
- жаргон из спек, который уже приходил в код (там же, «Прямой смысл, а не метафора и не жаргон»);
- гигиена диффа (docs/bsl-code-review.md, «Гигиена диффа перед коммитом»): BOM, CRLF, новые
  двойные пустые строки, «#Область» без пустой строки после неё, пустые строки, потерявшие таб;
- зарезервированные имена в модулях форм (docs/bsl-form-reserved-names.md): присвоение и Перем.

    python3 tools/diff-check/diff-check.py                 # рабочее дерево против HEAD
    python3 tools/diff-check/diff-check.py --база <коммит> # против базового коммита этапа
    python3 tools/diff-check/diff-check.py --индекс        # индекс против HEAD - перед коммитом
    python3 tools/diff-check/diff-check.py --файл <путь>   # один файл
    python3 tools/diff-check/diff-check.py --хук           # хук PostToolUse роли stage-executor

Новые неотслеживаемые файлы проверяются целиком. Код возврата: 0 - находок нет, 1 - есть,
2 - ошибка запуска. Запуск - из корня рабочего дерева.

Режим --хук читает JSON хука со stdin, проверяет только правленый .bsl и молчит, если находок
нет; находки - в stderr с кодом 2, их Claude Code показывает исполнителю сразу после правки.

Перед первым запуском заполнить блок «Настройка под проект» ниже.
"""
import argparse
import collections
import json
import os
import re
import subprocess
import sys

# --- Настройка под проект ---------------------------------------------------
# Префикс путей с кодом проекта: каталог EDT-проекта («<Каталог.Имя>/»); "" - весь репозиторий
КАТАЛОГ_КОДА = ""
# Каталоги, где правила вложенных вызовов и выровненных шагов не действуют: модули тестов и
# набор примеров самого скрипта проверки вложенных вызовов (он нарушает правило нарочно)
КАТАЛОГИ_БЕЗ_ПРАВИЛ = ("tools/nested-calls/",)
# Записанные артефакты, которые правило тире не трогает (bsl-coding-standards.md, «Тире»)
БЕЗ_ТИРЕ = ("specs/done/",)
# Путь-исключение правила тире (например, модуль с ключами запуска платформы); "" - нет
ИСКЛЮЧЕНИЕ_ТИРЕ = ""
# Стоп-лист жаргона спек - ЖАРГОН_СЛОВА ниже, рядом с разбором окончаний
# --- Конец настройки --------------------------------------------------------

ТИРЕ = re.compile("[\u2010-\u2015\u2212]")
ЗАРЕЗЕРВИРОВАННЫЕ = ("Параметры", "ПараметрыВыбора", "СвязиПараметровВыбора", "СписокВыбора",
                     "ПараметрыОтбора", "ОтборСтрок", "Окно", "Доступность", "Модифицированность",
                     "Заголовок")
ИМЯ_ЗАНЯТО = re.compile(r"^\s*(?:Перем\s+)?(" + "|".join(ЗАРЕЗЕРВИРОВАННЫЕ) + r")\s*[=;,]")
МОДУЛЬ_ФОРМЫ = re.compile(r"/Forms/[^/]+/Module\.bsl$")
ПРИСВАИВАНИЕ = re.compile(r"^(\t*)([^\W\d][\w.]*)([ \t]+)=(.*)$")
СТРОКА_1С = re.compile(r'"(?:[^"]|"")*"')
# Жаргон спек: стоп-лист проекта, пополняется по находкам владельца (bsl-coding-standards.md,
# «Прямой смысл, а не метафора и не жаргон»). Запись - (корень, окончания через «|», обязательно
# ли окончание): у «дирижёр» окончания нет в именительном падеже, у «пач» - есть всегда. Слово в
# прямом смысле - не находка, исполнитель оставляет его и называет в отчёте. Пустой кортеж -
# проверки нет. Пример:
# ЖАРГОН_СЛОВА = (("дирижёр", "ами|ам|ах|ов|ом|а|у|е|ы", False),
#                 ("пач", "ками|кам|ках|кой|ка|ки|ке|ку|ек", True))
ЖАРГОН_СЛОВА = ()
# Начало слова - после не-буквы или стык CamelCase (заглавная после строчной); конец - не строчная
ЖАРГОН = re.compile("|".join(
    rf"(?:(?<![^\W\d_])[{с[0]}{с[0].upper()}]|(?<=[а-яёa-z]){с[0].upper()}){с[1:]}(?:{окончания})"
    rf"{'' if обязательно else '?'}(?![а-яёa-z])"
    for с, окончания, обязательно in ЖАРГОН_СЛОВА)) if ЖАРГОН_СЛОВА else None
ЖАРГОН_ФАЙЛЫ = (".bsl", ".form", ".mdo")
BOM = b"\xef\xbb\xbf"
ПРЕДЕЛ = 15  # строк на одну проверку, остальное - числом


def git(*аргументы, байты=False):
    итог = subprocess.run(["git", "-c", "core.quotePath=false", *аргументы], capture_output=True)
    if итог.returncode != 0:
        sys.exit(f"git {' '.join(аргументы)}: {итог.stderr.decode('utf-8', 'replace').strip()}")
    return итог.stdout if байты else итог.stdout.decode("utf-8", "replace")


def код_проекта(путь):
    """Путь относится к коду проекта: там действуют правила вложенных вызовов и выровненных шагов."""
    return путь.startswith(КАТАЛОГ_КОДА) and not (КАТАЛОГИ_БЕЗ_ПРАВИЛ
                                                  and путь.startswith(КАТАЛОГИ_БЕЗ_ПРАВИЛ))


def пути_кода():
    """Pathspec кода проекта для git: каталог кода без каталогов, где правила не действуют."""
    итог = ([КАТАЛОГ_КОДА] if КАТАЛОГ_КОДА else []) + [f":(exclude){к}" for к in КАТАЛОГИ_БЕЗ_ПРАВИЛ]
    return ["--", *итог] if итог else []


def прочитать(путь):
    with open(путь, "rb") as файл:
        return файл.read()


def добавленные_строки(дифф):
    """{путь: [(номер, текст)]} по диффу -U0."""
    итог = collections.defaultdict(list)
    путь = None
    номер = 0
    for строка in дифф.splitlines():
        if строка.startswith("+++ "):
            путь = строка[6:] if строка.startswith("+++ b/") else None
        elif строка.startswith("@@"):
            номер = int(re.search(r"\+(\d+)", строка).group(1))
        elif путь and строка.startswith("+"):
            итог[путь].append((номер, строка[1:]))
            номер += 1
    return итог


def потерянные_табы(дифф):
    """{путь: число} пар «-<таб>» / «+» - пустые строки, переписанные без таба."""
    итог = collections.Counter()
    путь = None
    снято = добавлено = 0
    for строка in дифф.splitlines() + ["+++ конец"]:
        if строка.startswith("+++ ") or строка.startswith("@@"):
            if путь:
                итог[путь] += min(снято, добавлено)
            снято = добавлено = 0
            if строка.startswith("+++ "):
                путь = строка[6:] if строка.startswith("+++ b/") else None
        elif re.fullmatch(r"-\t+", строка):
            снято += 1
        elif строка == "+":
            добавлено += 1
    return {путь: число for путь, число in итог.items() if число and путь.endswith(".bsl")}


def лишние_пустые(стало, добавленные):
    """Добавленные строки, ломающие норму пустых строк в .bsl: двойная пустая строка и строка
    «#Область» без пустой строки после неё (docs/bsl-code-review.md, «Пустые строки»)."""
    строки = стало.split("\n")
    пустая = [not с.strip() for с in строки]
    двойные = [н + 1 for н in range(1, len(строки) - 1)
               if н + 1 in добавленные and пустая[н] and пустая[н - 1]]
    без_пустой = [н + 1 for н in range(len(строки) - 1)
                  if строки[н].lstrip().startswith("#Область")
                  and (н + 1 in добавленные or н + 2 in добавленные) and not пустая[н + 1]]
    итог = []
    if двойные:
        итог.append(f"двойная пустая строка: строки {двойные[:8]}")
    if без_пустой:
        итог.append(f"после #Область нет пустой строки: строки {без_пустой[:8]}")
    return итог


def колонка(текст):
    """Колонка конца текста на экране: таб - до следующей кратной 4."""
    итог = 0
    for символ in текст:
        итог = (итог // 4 + 1) * 4 if символ == "\t" else итог + 1
    return итог


def зависимые_в_блоке(блок, добавленные):
    """Пары строк выровненного блока, где имя из левой части идёт в правую часть следующей."""
    if len(блок) < 2 or not any("\t" in промежуток or len(промежуток) > 1
                                for _, _, промежуток, _ in блок):
        return []
    итог = []
    for и, (номер, _, _, правая) in enumerate(блок):
        текст = СТРОКА_1С.sub('""', правая).split("//")[0]
        for прежний, имя, _, _ in блок[:и]:
            if "." in имя or (прежний not in добавленные and номер not in добавленные):
                continue
            if re.search(rf"(?<![\w.]){re.escape(имя)}(?!\w)", текст):
                итог.append(f"строки {прежний} и {номер}: «{имя}» идёт в следующий шаг")
                break
    return итог


def выровненные_зависимые(стало, добавленные):
    """Выровненные по «=» соседние строки, где результат строки идёт аргументом в следующую
    (docs/bsl-coding-standards.md, «Вложенные вызовы - всегда в переменную», последний абзац).
    Блок - подряд идущие присваивания с одним отступом и «=» в одной колонке; выровнен, если
    хотя бы у одной строки перед «=» таб или больше одного пробела."""
    итог = []
    блок = []
    место_блока = None
    for номер, строка in enumerate(стало.split("\n") + [""], 1):
        найдено = ПРИСВАИВАНИЕ.match(строка)
        место = None
        if найдено:
            отступ, имя, промежуток, _ = найдено.groups()
            место = (отступ, колонка(отступ + имя + промежуток))
        if блок and место != место_блока:
            итог += зависимые_в_блоке(блок, добавленные)
            блок = []
        if найдено:
            блок.append((номер, имя, промежуток, найдено.group(4)))
            место_блока = место
    return итог


def путь_из_хука():
    """Путь правленого .bsl от корня рабочего дерева из JSON хука; не .bsl - None.

    Переходит в корень рабочего дерева: проверки зовут скрипты по относительным путям.
    """
    try:
        данные = json.load(sys.stdin)
    except ValueError:
        return None
    ввод = данные.get("tool_input") or {}
    путь = ввод.get("file_path") or ввод.get("path") or ввод.get("target_path") or ""
    if not путь.endswith(".bsl"):
        return None
    if not os.path.isabs(путь):
        путь = os.path.join(данные.get("cwd") or os.getcwd(), путь)
    корень = subprocess.run(["git", "-C", os.path.dirname(путь), "rev-parse", "--show-toplevel"],
                           capture_output=True, text=True).stdout.strip()
    if not корень:
        return None
    os.chdir(корень)
    return os.path.relpath(путь, корень)


def main():
    разбор = argparse.ArgumentParser(description="Механические проверки диффа")
    разбор.add_argument("--база", default="HEAD", help="базовый коммит (по умолчанию HEAD)")
    разбор.add_argument("--индекс", action="store_true", help="проверять индекс, а не рабочее дерево")
    разбор.add_argument("--файл", help="проверить один файл (путь от корня рабочего дерева)")
    разбор.add_argument("--хук", action="store_true",
                        help="хук PostToolUse: путь из JSON на stdin, находки - в stderr с кодом 2")
    аргументы = разбор.parse_args()
    if аргументы.хук:
        аргументы.файл = путь_из_хука()
        if not аргументы.файл:
            sys.exit(0)

    область = ["--cached", аргументы.база] if аргументы.индекс else [аргументы.база]
    пути = ["--", аргументы.файл] if аргументы.файл else []
    дифф = git("diff", "-U0", "--no-color", "--no-ext-diff", *область, *пути)
    изменённые = [п for п in git("diff", "--name-only", "--diff-filter=AMR", *область, *пути).splitlines() if п]
    новые = [] if аргументы.индекс else [п for п in git("ls-files", "--others", "--exclude-standard", *пути).splitlines() if п]

    находки = collections.defaultdict(list)

    # Вложенные вызовы: дифф модулей кода проекта и новые модули целиком (тесты правило не проверяет)
    if аргументы.файл:
        дифф_кода = (git("diff", "-U0", "--no-color", "--no-ext-diff", *область, "--",
                         аргументы.файл, байты=True) if код_проекта(аргументы.файл) else b"")
    else:
        дифф_кода = git("diff", "-U0", "--no-color", "--no-ext-diff", *область, *пути_кода(), байты=True)
    проходы = [subprocess.run(["perl", "tools/nested-calls/nested-calls.pl", "--diff"],
                              input=дифф_кода, capture_output=True)]
    новые_модули = [п for п in новые if код_проекта(п) and п.endswith(".bsl")]
    if новые_модули:
        проходы.append(subprocess.run(["perl", "tools/nested-calls/nested-calls.pl", *новые_модули],
                                      capture_output=True))
    for проход in проходы:
        if проход.returncode == 2:
            sys.exit("nested-calls.pl: " + проход.stderr.decode("utf-8", "replace").strip())
        находки["вложенные вызовы"] += проход.stdout.decode("utf-8", "replace").splitlines()

    # Добавленные строки: тире, жаргон и зарезервированные имена
    добавлено = добавленные_строки(дифф)
    for путь in новые:
        try:
            текст = прочитать(путь).decode("utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        добавлено[путь] = list(enumerate(текст.splitlines(), 1))
    for путь, строки in добавлено.items():
        for номер, текст in строки:
            if ТИРЕ.search(текст) and not путь.startswith(БЕЗ_ТИРЕ):
                пометка = (" (путь в исключениях правила - проверить причину)"
                           if ИСКЛЮЧЕНИЕ_ТИРЕ and ИСКЛЮЧЕНИЕ_ТИРЕ in путь else "")
                находки["тире"].append(f"{путь}:{номер}: {текст.strip()[:90]}{пометка}")
            if ЖАРГОН and код_проекта(путь) and путь.endswith(ЖАРГОН_ФАЙЛЫ):
                слово = ЖАРГОН.search(текст)
                if слово:
                    находки["жаргон"].append(f"{путь}:{номер}: «{слово.group(0)}» - {текст.strip()[:80]}")
            if МОДУЛЬ_ФОРМЫ.search(путь) and ИМЯ_ЗАНЯТО.match(текст):
                находки["зарезервированные имена форм"].append(f"{путь}:{номер}: {текст.strip()[:90]}")

    # Гигиена: BOM, CRLF и пустые строки - по файлу целиком против базы
    for путь in изменённые + новые:
        try:
            стало = git("show", f":{путь}", байты=True) if аргументы.индекс else прочитать(путь)
        except OSError:
            continue
        было = b""
        if путь not in новые:
            показ = subprocess.run(["git", "-c", "core.quotePath=false", "show", f"{аргументы.база}:{путь}"],
                                   capture_output=True)
            было = показ.stdout if показ.returncode == 0 else b""
        бом_было = было.startswith(BOM)
        бом_стало = стало.startswith(BOM)
        if было and бом_было != бом_стало:
            находки["кодировка"].append(f"{путь}: BOM {'появился' if бом_стало else 'пропал'}")
        if b"\r\n" in стало and b"\r\n" not in было:
            находки["переводы строк"].append(f"{путь}: CRLF вместо LF")
        if путь.endswith(".bsl"):
            номера = {номер for номер, _ in добавлено.get(путь, [])}
            текст = стало.decode("utf-8", "replace")
            for запись in лишние_пустые(текст, номера):
                находки["пустые строки"].append(f"{путь}: {запись}")
            # Модули тестов правило вложенных вызовов не проверяет - и его последний абзац тоже
            if код_проекта(путь):
                for запись in выровненные_зависимые(текст, номера):
                    находки["выровненные шаги"].append(f"{путь}: {запись}")
    for путь, число in потерянные_табы(дифф).items():
        находки["пустые строки"].append(f"{путь}: {число} пустых строк потеряли таб (пары «-<таб>» / «+»)")

    вывод = []
    for проверка in ("вложенные вызовы", "выровненные шаги", "тире", "жаргон",
                     "зарезервированные имена форм", "кодировка", "переводы строк", "пустые строки"):
        строки = находки.get(проверка) or []
        if not строки:
            continue
        вывод.append(f"[{проверка}] {len(строки)}")
        вывод += [f"  {строка}" for строка in строки[:ПРЕДЕЛ]]
        if len(строки) > ПРЕДЕЛ:
            вывод.append(f"  ... и ещё {len(строки) - ПРЕДЕЛ}")
    есть = bool(вывод)
    if аргументы.хук:
        if есть:
            print(f"diff-check после правки {аргументы.файл}:", file=sys.stderr)
            print("\n".join(вывод), file=sys.stderr)
            print("Исправь до отчёта; промежуточное состояние незаконченной правки - не находка.", file=sys.stderr)
        sys.exit(2 if есть else 0)
    if есть:
        print("\n".join(вывод))
    else:
        print(f"Находок нет: вложенные вызовы, выровненные шаги, тире, жаргон, зарезервированные "
              f"имена форм, гигиена диффа ({len(изменённые) + len(новые)} файлов)")
    sys.exit(1 if есть else 0)


if __name__ == "__main__":
    main()
