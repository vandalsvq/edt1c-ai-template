#!/usr/bin/perl
# Проход по правилам docs/bsl-coding-standards.md «Вложенные вызовы - всегда в переменную»
# и «Коллекция цикла - в переменной»: вызов с параметрами в аргументе другого вызова (кроме
# исключений правила) и вызов в заголовке «Для Каждого ... Из ... Цикл» - кроме простого
# метода платформы и одного вызова без параметров.
#
# Модули тестов правило не проверяет - путь их каталога в проход не передаётся.
#
# Запуск:
#   perl tools/nested-calls/nested-calls.pl <модуль.bsl>...
#       все нарушения в модулях;
#   git diff -U0 <база> | perl tools/nested-calls/nested-calls.pl --diff [--root <каталог>]
#       только операторы, которые задевают добавленные строки диффа. Модули берутся из диффа,
#       пути - от --root (по умолчанию текущий каталог - корень рабочего дерева).
#
# Вывод: <файл>:<строка начала оператора>: <что нашлось>.
# Код возврата: 0 - нарушений нет, 1 - есть, 2 - ошибка запуска.
#
# Разбор - построчный, со сквозным учётом строковых литералов, комментариев и скобок; типы
# выражений не выводятся. Исключение «простые методы платформы» держится на перечне
# %ПростыеМетоды ниже - его же правило в bsl-coding-standards.md называет перечнем.
#
# После правки скрипта - самопроверка: находки по cases.bsl должны совпасть со строками «// ДА»:
#   diff <(perl -ne 'print "$.\n" if m{// ДА}' tools/nested-calls/cases.bsl) \
#        <(perl tools/nested-calls/nested-calls.pl tools/nested-calls/cases.bsl | perl -ne '/:(\d+):/ and print "$1\n"')

use strict;
use warnings;
use utf8;

binmode STDOUT, ':encoding(UTF-8)';
binmode STDERR, ':encoding(UTF-8)';

# Вызовы, которые могут стоять в аргументе (их собственные аргументы проверяются).
my %Исключения = map { lc($_) => 1 } (
	'НСтр', 'ПредопределенноеЗначение', 'Тип', 'ТипЗнч',
	'ОбработкаОшибок.ПодробноеПредставлениеОшибки', 'ОбработкаОшибок.КраткоеПредставлениеОшибки',
);

# Конструктор «Новый <Тип>(...)» может стоять в аргументе любого вызова (его аргументы
# проверяются); ограничение одно - «Новый Структура» не больше чем с тремя ключами.
my $Конструктор = qr/^Новый\s/i;

# Методы коллекций, в аргументе которых допустим вызов метода модуля или объекта (на один
# уровень: аргументы этого вызова проверяются).
my $ВызовыСМетодомВАргументе = qr/(?:^|\.)(?:Вставить|Добавить)$/i;

# Простые методы платформы над строками, числами, датами, булевыми значениями и УИД: допустимы
# в аргументе любого вызова и друг в друге на любую глубину. Внутри одного такого метода
# (не двух подряд) допустим и метод модуля или объекта.
my %ПростыеМетоды = map { lc($_) => 1 } (
	# строки
	qw(
		СокрЛ СокрП СокрЛП Лев Прав Сред НРег ВРег ТРег СтрДлина СтрНайти СтрЗаменить СтрСоединить
		СтрРазделить СтрПолучитьСтроку СтрЧислоСтрок СтрЧислоВхождений СтрНачинаетсяС
		СтрЗаканчиваетсяНа СтрСравнить СтрШаблон ПустаяСтрока Символ КодСимвола Формат Строка XMLСтрока
	),
	# числа
	qw(Окр Цел Мин Макс Pow Sqrt Exp Log Log10 Sin Cos Tan ASin ACos ATan Число),
	# даты
	qw(
		НачалоДня КонецДня НачалоНедели КонецНедели НачалоМесяца КонецМесяца НачалоКвартала
		КонецКвартала НачалоГода КонецГода НачалоЧаса КонецЧаса НачалоМинуты КонецМинуты
		ДобавитьМесяц Год Месяц День Час Минута Секунда ДеньГода ДеньНедели НеделяГода Дата
		МестноеВремя УниверсальноеВремя
	),
	# булево и УИД
	'Булево', 'ЗначениеЗаполнено', 'Новый УникальныйИдентификатор',
);

# Глобальные представления ошибки - в аргументе только этих вызовов.
my %ПредставленияОшибки = map { lc($_) => 1 } ('КраткоеПредставлениеОшибки', 'ПодробноеПредставлениеОшибки');
my $ВызовыСПредставлениемОшибки = qr/(?:^|\.)(?:СтрШаблон|ПодставитьПараметрыВСтроку)$/i;

# Слова перед скобкой, которые не делают её вызовом.
my %КлючевыеСлова = map { lc($_) => 1 } qw(
	Если ИначеЕсли Иначе Тогда И ИЛИ НЕ Возврат Для Каждого Из По Пока Цикл ВызватьИсключение
	Ждать Знач Экспорт Новый
);

my ($РежимДиффа, $Корень) = (0, '.');
my @Файлы;
while (@ARGV) {
	my $Арг = shift @ARGV;
	if    ($Арг eq '--diff') { $РежимДиффа = 1; }
	elsif ($Арг eq '--root') { $Корень = shift @ARGV // Использование(); }
	elsif ($Арг =~ /^-/)     { Использование(); }
	else                     { push @Файлы, $Арг; }
}
Использование() if $РежимДиффа && @Файлы;
Использование() if !$РежимДиффа && !@Файлы;

my $Найдено = 0;

if ($РежимДиффа) {
	my $Добавленные = ДобавленныеСтроки();
	for my $Путь (sort keys %$Добавленные) {
		my $ПолныйПуть = "$Корень/$Путь";
		unless (-f $ПолныйПуть) {
			print STDERR 'нет файла: ', Текст($ПолныйПуть), "\n";
			next;
		}
		ПроверитьФайл($ПолныйПуть, $Путь, $Добавленные->{$Путь});
	}
} else {
	ПроверитьФайл($_, $_, undef) for @Файлы;
}

exit($Найдено ? 1 : 0);

sub Использование {
	print STDERR "Запуск: nested-calls.pl <модуль.bsl>...\n";
	print STDERR "        git diff -U0 <база> | nested-calls.pl --diff [--root <каталог>]\n";
	exit 2;
}

sub Текст {
	my ($Байты) = @_;
	my $Строка = $Байты;
	utf8::decode($Строка);
	return $Строка;
}

# Номера добавленных строк по модулям .bsl из унифицированного диффа на STDIN.
sub ДобавленныеСтроки {
	my (%Добавленные, $Путь, $Номер);
	my $ВКуске = 0;
	while (my $Строка = <STDIN>) {
		$Строка =~ s/\r?\n\z//;
		if ($Строка =~ /^diff /) {
			($Путь, $ВКуске) = (undef, 0);
		} elsif (!$ВКуске && $Строка =~ /^\+\+\+ (.*)$/) {
			my $Имя = $1;
			$Имя =~ s/\t.*$//;
			if ($Имя =~ /^"(.*)"$/) {
				$Имя = $1;
				$Имя =~ s/\\([0-7]{3})/chr(oct $1)/ge;
				$Имя =~ s/\\(.)/$1/g;
			}
			$Имя =~ s{^b/}{};
			$Путь = ($Имя ne '/dev/null' && $Имя =~ /\.bsl$/i) ? $Имя : undef;
		} elsif ($Строка =~ /^@@ -\S+ \+(\d+)(?:,\d+)? @@/) {
			($Номер, $ВКуске) = ($1, 1);
		} elsif ($ВКуске && defined $Путь) {
			if    ($Строка =~ /^\+/) { $Добавленные{$Путь}{$Номер++} = 1; }
			elsif ($Строка =~ /^ /)  { $Номер++; }
		}
	}
	return \%Добавленные;
}

sub ПроверитьФайл {
	my ($ПолныйПуть, $ВыводимыйПуть, $Добавленные) = @_;

	open my $Поток, '<:raw', $ПолныйПуть or do {
		print STDERR 'не открывается: ', Текст($ПолныйПуть), "\n";
		return;
	};
	my @Строки = <$Поток>;
	close $Поток;

	my $Имя = Текст($ВыводимыйПуть);
	for my $Оператор (@{ Операторы(\@Строки) }) {
		next unless @{ $Оператор->{Находки} };
		if ($Добавленные) {
			my $Задет = grep { $Добавленные->{$_} } $Оператор->{Начало} .. $Оператор->{Конец};
			next unless $Задет;
		}
		for my $Находка (@{ $Оператор->{Находки} }) {
			print "$Имя:$Оператор->{Начало}: $Находка\n";
			$Найдено++;
		}
	}
}

# Разбирает модуль на операторы: оператор - строки до закрытия всех скобок в конце строки.
sub Операторы {
	my ($Строки) = @_;
	my @Операторы;
	my $ВСтроке = 0;
	my @Скобки;   # кадры: {Имя => имя вызова или '', Группы => {...}, Цепочка => N}
	my $Текущий = НовыйОператор();

	for my $Индекс (0 .. $#$Строки) {
		my $Номер = $Индекс + 1;
		my $Строка = $Строки->[$Индекс];
		utf8::decode($Строка);
		$Строка =~ s/\r?\n\z//;

		my $Позиция = 0;
		my $Длина = length $Строка;
		while ($Позиция < $Длина) {
			my $Символ = substr($Строка, $Позиция, 1);
			if ($ВСтроке) {
				if ($Символ eq '"') {
					if (substr($Строка, $Позиция + 1, 1) eq '"') { $Позиция += 2; next; }
					$ВСтроке = 0;
				}
				$Позиция++;
				next;
			}
			last if substr($Строка, $Позиция, 2) eq '//';
			$Текущий->{Начало} ||= $Номер if $Символ =~ /\S/;
			if ($Символ eq '"') {
				$ВСтроке = 1;
				$Текущий->{Текст} .= '""';
				$Позиция++;
				next;
			}
			if ($Символ eq '(') {
				my $Кадр = КадрСкобки(substr($Строка, 0, $Позиция), substr($Строка, $Позиция + 1), \@Скобки,
					$Текущий);
				push @Скобки, $Кадр;
			} elsif ($Символ eq ')') {
				pop @Скобки;
			}
			$Текущий->{Текст} .= $Символ;
			$Позиция++;
		}
		$Текущий->{Текст} .= ' ';
		$Текущий->{Конец} = $Номер;

		if (!$ВСтроке && !@Скобки) {
			if ($Текущий->{Начало}) {
				ПроверитьЦикл($Текущий);
				push @Операторы, $Текущий;
			}
			$Текущий = НовыйОператор();
		}
	}
	return \@Операторы;
}

sub НовыйОператор {
	return { Начало => 0, Конец => 0, Текст => '', Находки => [] };
}

# Кадр открывающей скобки; вызов с параметрами внутри другого вызова - находка оператора.
sub КадрСкобки {
	my ($До, $После, $Скобки, $Оператор) = @_;

	my $Имя = '';
	if ($До =~ /((?:Новый\s+)?[\w.]+)\s*\z/i) {
		$Имя = $1;
		$Имя =~ s/^новый\s+/Новый /i;
	}
	$Имя = '' if $КлючевыеСлова{lc $Имя} || $Имя =~ /^[\d.]+$/;
	$Имя =~ s/^\.//;

	my ($Внешний) = grep { $_->{Имя} ne '' } reverse @$Скобки;

	# Цепочка - сколько простых методов подряд заканчивается этим вызовом.
	my $Цепочка = 0;
	if ($Имя ne '' && $ПростыеМетоды{lc $Имя}) {
		$Цепочка = $Внешний ? $Внешний->{Цепочка} + 1 : 1;
	}
	my $Кадр = { Имя => $Имя, Цепочка => $Цепочка };

	return $Кадр if $Имя eq '' || !$Внешний;
	return $Кадр if $После =~ /^\s*\)/;             # вызов без параметров
	return $Кадр if $Исключения{lc $Имя};
	return $Кадр if $Цепочка;                       # простой метод - в любом вызове, на любую глубину
	return $Кадр if $Внешний->{Цепочка} == 1;               # метод модуля внутри одного простого метода
	return $Кадр if $ПредставленияОшибки{lc $Имя} && $Внешний->{Имя} =~ $ВызовыСПредставлениемОшибки;
	if (lc($Имя) eq 'новый структура') {
		# Ограничение ключей действует и в аргументе Вставить / Добавить.
		my ($Ключи) = $После =~ /^\s*"([^"]*)"/;
		return $Кадр if defined $Ключи && scalar(grep { /\S/ } split /,/, $Ключи) <= 3;
	} else {
		return $Кадр if $Имя =~ $Конструктор;
		return $Кадр if $Внешний->{Имя} =~ $ВызовыСМетодомВАргументе;
	}

	push @{ $Оператор->{Находки} }, "вызов $Имя(...) в аргументе $Внешний->{Имя}(...)";
	return $Кадр;
}

sub ПроверитьЦикл {
	my ($Оператор) = @_;
	return unless $Оператор->{Текст} =~ /^\s*Для\s+Каждого\s+\S+\s+Из\s+(.*?)\s+Цикл\b/i;
	my $Коллекция = $1;
	return unless $Коллекция =~ /\(/;
	# Один вызов без параметров, не цепочка: Из ОписаниеТипов.Типы().
	return if $Коллекция =~ /^\s*[\w.]+\s*\(\s*\)\s*$/;
	# Простой метод платформы на всё выражение: Из СтрРазделить(Строка, ","). Его аргументы
	# проверяет правило вложенных вызовов.
	if ($Коллекция =~ /^\s*([\w]+)\s*\(/ && $ПростыеМетоды{lc $1}) {
		return if ЗакрывающаяСкобкаВКонце($Коллекция);
	}
	push @{ $Оператор->{Находки} }, "вызов в заголовке цикла: Из $Коллекция";
}

# Истина, если первая открывающая скобка выражения закрывается последним его символом.
sub ЗакрывающаяСкобкаВКонце {
	my ($Выражение) = @_;
	$Выражение =~ s/\s+\z//;
	my $Глубина = 0;
	my $Начало = index($Выражение, '(');
	for my $Позиция ($Начало .. length($Выражение) - 1) {
		my $Символ = substr($Выражение, $Позиция, 1);
		$Глубина++ if $Символ eq '(';
		$Глубина-- if $Символ eq ')';
		return ($Позиция == length($Выражение) - 1) if $Глубина == 0;
	}
	return 0;
}
