#!/usr/bin/env python3
"""Прогон модулей YAxUnit в рабочей базе и отбор тестов по диффу ветки

Шаги 2-4 прогона в рабочей базе одной командой - docs/yaxunit-bootstrap.md §6.1 (там же грабли
ручного пути). Базу перед прогоном обновляет агент (update_infobase через codepilot1c), скрипт
его не зовёт: он проверяет, что обновление дошло, и останавливается, если база старше исходников.

    python3 tools/yaxunit/yaxunit.py --модули prj_ТестОбъект prj_ТестДругойОбъект
    python3 tools/yaxunit/yaxunit.py --дифф [--база-ветки origin/develop] [--только-отбор]
    python3 tools/yaxunit/yaxunit.py --все          # всё тестовое расширение, без пишущих данные

Код возврата: 0 - все тесты прошли, 1 - есть красные, 2 - прогон не состоялся или его
результату нельзя верить (стенд), в том числе скрипт не настроен. Последняя строка вывода -
«ВЕРДИКТ:» с причиной; ошибка запуска (настройка, конфиг стенда) - в stderr.

Что делает сам:
- до запуска сравнивает время последней строки «Загрузка N объектов конфигурации в
  информационную базу <база>» в логе EDT с самым свежим файлом src обоих проектов: файл новее -
  код 2 без прогона (так ловится ложный зелёный);
- пишет run.json, запускает клиент с ключом /C RunUnitTests и держит дедлайн; клиент без отчёта
  повторяет, при отказе лицензии разработчика может снять агента конфигуратора EDT (macOS,
  файловая база, ключ конфига сниматьАгентаКонфигуратора);
- выносит вердикт по exitcode.txt (пишется с BOM) и report.xml свежее старта, не по коду процесса;
- по логу YAxUnit сверяет версию основного расширения с Configuration.mdo и снятый безопасный
  режим у движка и тестового расширения;
- пропускает и называет модули, пишущие данные (ПИШУТ_ДАННЫЕ), если база рабочая;
- при --дифф берёт модуль, если он или его серверная пара обращается к затронутому объекту по
  имени, плюс изменённые тестовые модули; затронутое без такого модуля - строкой «не покрыты».

Конфиг стенда машины - tools/yaxunit/stand.json (в .gitignore), образец - stand.example.json
рядом. Из worktree без своего stand.json берётся конфиг основного рабочего дерева. Логин и
пароль базы читаются из файла учетки и не печатаются.

Перед первым запуском заполнить блок «Настройка под проект» ниже; без него скрипт отказывается
с кодом 2. Предполагается: тесты - отдельное расширение, база файловая, EDT ведёт
<воркспейс>/.metadata/.log. Python 3.9+. Проверено 2026-10 на одном проекте, macOS, файловая
база; ветки Windows (пути, снятие клиента) и серверной базы не проверялись.
"""

