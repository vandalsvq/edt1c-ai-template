def записать_run_json(каталог: Path, модули: list[str] | None) -> Path:
    фильтр: dict = {"extensions": [РАСШИРЕНИЕ_ТЕСТОВ]}
    if модули is not None:
        фильтр["modules"] = модули
    настройки = {
        "filter": фильтр,
        "reportFormat": "jUnit",
        "reportPath": str(каталог / "report.xml"),
        "closeAfterTests": True,
        "showReport": False,
        "exitCode": str(каталог / "exitcode.txt"),
        "logging": {"file": str(каталог / "yax.log"), "console": False, "level": "debug"},
    }
    путь = каталог / "run.json"
    путь.write_text(json.dumps(настройки, ensure_ascii=False, indent=2), encoding="utf-8")
    json.loads(путь.read_text(encoding="utf-8"))
    return путь


def прочитать(путь: Path) -> str:
    return путь.read_text(encoding="utf-8-sig", errors="replace").strip() if путь.exists() else ""


def запустить(конфиг: dict, каталог: Path, run_json: Path, дедлайн: int) -> float:
    """Запускает клиент до появления свежего отчета; возвращает время старта удачной попытки."""
    пользователь, пароль = учетка(конфиг.get("учетка"))
    аргументы = [конфиг["клиент"], "ENTERPRISE", *конфиг["подключение"]]
    if пользователь:
        аргументы += ["/N", пользователь]
    if пароль:
        аргументы += ["/P", пароль]  # пустой /P не передавать: паролем станет следующий ключ
    аргументы += ["/C", f"RunUnitTests={run_json}", "/Out", str(каталог / "ent.log"),
                  "/DisableStartupDialogs", "/DisableStartupMessages"]
    отчет = каталог / "report.xml"
    агент_снят = False
    for попытка in range(1, ПОПЫТОК + 1):
        for имя in ("report.xml", "exitcode.txt", "yax.log", "ent.log"):
            (каталог / имя).unlink(missing_ok=True)
        старт = time.time()
        try:
            процесс = subprocess.Popen(аргументы, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        except OSError as ошибка:
            raise ОшибкаСтенда(f"клиент не запустился ({конфиг['клиент']}): {ошибка}")
        try:
            процесс.wait(timeout=дедлайн)
        except subprocess.TimeoutExpired:
            как = снять(процесс)
            raise ОшибкаСтенда(f"клиент снят по дедлайну {дедлайн} с ({как}); "
                               f"ent.log: {прочитать(каталог / 'ent.log') or 'пусто'}")
        длительность = time.time() - старт
        print(f"Прогон: попытка {попытка}, клиент {длительность:.0f} с, код процесса {процесс.returncode}")
        if отчет.exists() and отчет.stat().st_mtime >= старт:
            return старт
        лог = прочитать(каталог / "ent.log") or "пусто"
        if ПРИЗНАК_ЛИЦЕНЗИИ in лог:
            if конфиг.get("сниматьАгентаКонфигуратора") and not агент_снят and попытка < ПОПЫТОК:
                снять_агента_конфигуратора(конфиг)
                агент_снят = True
                continue
            raise ОшибкаСтенда(
                "лимит клиентов лицензии разработчика. На macOS счетчик сеансов живет в агенте "
                "конфигуратора, которым EDT обновляет базу (1cv8 DESIGNER /AgentMode), и клиенты, "
                "снятые по дедлайну, остаются в нем: снять этот процесс (EDT поднимет его при "
                "следующем update_infobase) или включить сниматьАгентаКонфигуратора в конфиге; "
                f"ent.log: {лог}")
        if длительность < ПОРОГ_БЫСТРОГО_ВЫХОДА and попытка < ПОПЫТОК:
            print(f"  клиент закрылся без отчета; ent.log: {лог}; пауза {ПАУЗА_ПОВТОРА} с и повтор")
            time.sleep(ПАУЗА_ПОВТОРА)
            continue
        raise ОшибкаСтенда(
            f"отчета нет: клиент закрылся без прогона (нет движка {ДВИЖОК}, он в безопасном "
            f"режиме, или отказ платформы); ent.log: {лог}")
    raise ОшибкаСтенда("отчета нет после всех попыток")


def снять(процесс: subprocess.Popen) -> str:
    """Снимает зависший клиент: сначала просьбой завершиться, затем принудительно."""
    процесс.terminate()
    try:
        процесс.wait(timeout=МЯГКОЕ_СНЯТИЕ)
        return "завершился по просьбе"
    except subprocess.TimeoutExpired:
        процесс.kill()
        процесс.wait()
        return "снят принудительно"


def снять_агента_конфигуратора(конфиг: dict) -> None:
    """Завершает агент конфигуратора EDT для файловой базы стенда: вместе с ним сбрасывается
    счетчик сеансов лицензии разработчика. EDT поднимает агента при следующем обновлении базы."""
    подключение = конфиг["подключение"]
    if os.name == "nt" or len(подключение) != 2 or подключение[0] != "/F":
        raise ОшибкаСтенда("снятие агента конфигуратора - только для файловой базы на macOS и Linux")
    путь = подключение[1]
    список = subprocess.run(["ps", "-axo", "pid=,command="], capture_output=True, text=True,
                            encoding="utf-8", errors="replace").stdout
    база = re.compile(re.escape("/F" + путь) + r"(\s|$)")
    агенты = []
    for строка in список.splitlines():
        номер, _, команда = строка.strip().partition(" ")
        if (" DESIGNER " in команда and "/AgentMode" in команда
                and база.search(команда.replace("/F ", "/F"))):
            агенты.append(int(номер))
    if not агенты:
        raise ОшибкаСтенда("отказ лицензии, а агента конфигуратора для базы нет: базу держат другие клиенты")
    for номер in агенты:
        os.kill(номер, signal.SIGTERM)
    срок = time.time() + 10
    while time.time() < срок and any(жив(номер) for номер in агенты):
        time.sleep(0.5)
    for номер in агенты:
        if жив(номер):
            os.kill(номер, signal.SIGKILL)
    print(f"  отказ лицензии: снят агент конфигуратора EDT (pid {', '.join(map(str, агенты))}) - "
          f"счетчик сеансов сброшен, EDT поднимет агента при следующем update_infobase; повтор")


def жив(номер: int) -> bool:
    try:
        os.kill(номер, 0)
        return True
    except ProcessLookupError:
        return False


