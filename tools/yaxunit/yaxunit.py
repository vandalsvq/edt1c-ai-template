def разобрать_отчет(отчет: Path) -> dict:
    итог = {"всего": 0, "прошло": 0, "пропущено": 0, "красные": []}
    for случай in ET.parse(отчет).getroot().iter("testcase"):
        итог["всего"] += 1
        падение = случай.find("failure")
        if падение is None:
            падение = случай.find("error")
        имя, класс = случай.get("name", ""), случай.get("classname", "")
        полное = класс if класс.endswith(имя) else f"{класс}.{имя}"
        if падение is not None:
            итог["красные"].append((полное, падение.get("message", "").strip()))
        elif случай.find("skipped") is not None:
            итог["пропущено"] += 1
        else:
            итог["прошло"] += 1
    return итог


def расширения_из_лога(лог: Path) -> dict[str, dict[str, str]]:
    """Имя расширения -> {Версия, БезопасныйРежим} из перечня в начале лога YAxUnit."""
    расширения: dict[str, dict[str, str]] = {}
    текущее = None
    for строка in прочитать(лог).splitlines()[:300]:
        совпадение = re.match(r"^\s*- (Имя|Версия|БезопасныйРежим): (.*)$", строка)
        if not совпадение:
            continue
        ключ, значение = совпадение.group(1), совпадение.group(2).strip()
        if ключ == "Имя":
            текущее = расширения.setdefault(значение, {})
        elif текущее is not None:
            текущее[ключ] = значение
    return расширения


def версия_исходников(исходники: Path) -> str:
    текст = прочитать(исходники / ПРОЕКТ / "src" / "Configuration" / "Configuration.mdo")
    совпадение = re.search(r"<version>([^<]+)</version>", текст)
    return совпадение.group(1) if совпадение else ""


def замечания_стенда(каталог: Path, исходники: Path) -> list[str]:
    расширения = расширения_из_лога(каталог / "yax.log")
    if not расширения:
        return ["в логе YAxUnit нет перечня расширений - версию и безопасный режим не проверить"]
    замечания = []
    режимы = ", ".join(f"{имя} {расширения.get(имя, {}).get('БезопасныйРежим', '?')}"
                       for имя in (ДВИЖОК, РАСШИРЕНИЕ_ТЕСТОВ))
    if РАСШИРЕНИЕ:
        в_базе, в_исходниках = расширения.get(РАСШИРЕНИЕ, {}).get("Версия"), версия_исходников(исходники)
        print(f"Расширения: {РАСШИРЕНИЕ} {в_базе} (исходники {в_исходниках}); безопасный режим: {режимы}")
        if в_базе != в_исходниках:
            замечания.append(f"версия {РАСШИРЕНИЕ} в базе {в_базе}, в исходниках {в_исходниках}: "
                             f"база не на этом коде")
    else:
        print(f"Расширения: версия основного кода не сверялась (основной проект - конфигурация); "
              f"безопасный режим: {режимы}")
    for имя in (ДВИЖОК, РАСШИРЕНИЕ_ТЕСТОВ):
        if расширения.get(имя, {}).get("БезопасныйРежим") != "Нет":
            замечания.append(f"у {имя} не снят безопасный режим")
    return замечания


def вердикт(итог: dict, код_движка: str, замечания: list[str]) -> tuple[int, str]:
    """Код возврата и последняя строка по отчету, exitcode.txt и замечаниям стенда."""
    if замечания:
        return КОД_СТЕНД, "ВЕРДИКТ: стенд - " + "; ".join(замечания)
    if итог["красные"] or код_движка not in ("0", ""):
        return КОД_КРАСНЫЙ, "ВЕРДИКТ: красный"
    if итог["всего"] == 0:
        return КОД_СТЕНД, "ВЕРДИКТ: стенд - в отчете нет ни одного теста"
    return КОД_ЗЕЛЕНЫЙ, "ВЕРДИКТ: зеленый"


