def составить_отбор(аргументы, конфиг: dict, исходники: Path) -> tuple[list[str] | None, list[str]]:
    """Возвращает модули для фильтра (None - все расширение целиком) и пропущенные пишущие."""
    модули = тестовые_модули(исходники)
    if аргументы.модули:
        неизвестные = [имя for имя in аргументы.модули if имя not in модули]
        if неизвестные:
            raise ОшибкаСтенда(f"не тестовые модули {ПРОЕКТ_ТЕСТОВ}: {', '.join(неизвестные)}")
        отобраны = list(аргументы.модули)
        print(f"Отбор: названные модули ({len(отобраны)})")
    elif аргументы.все:
        отобраны = модули
        print(f"Отбор: все тестовые модули ({len(отобраны)})")
    else:
        база = аргументы.база_ветки or база_ветки_по_умолчанию(исходники)
        карта = карта_покрытия(исходники, модули, объекты_продукта(исходники))
        дифф = отбор_по_диффу(исходники, база, модули, карта)
        отобраны = дифф["модули"]
        print(f"Отбор: дифф против {база} (merge-base {дифф['точка']}), затронуто объектов "
              f"{len(дифф['затронуты'])}")
        print(f"  не покрыты ({len(дифф['не_покрыты'])}): {', '.join(дифф['не_покрыты']) or 'нет'}")
    пропущены = [м for м in отобраны if конфиг["рабочаяБаза"] and м in ПИШУТ_ДАННЫЕ]
    отобраны = [м for м in отобраны if м not in пропущены]
    print(f"  модули ({len(отобраны)}): {', '.join(отобраны) or 'нет'}")
    if пропущены:
        print(f"  пропущены, пишут данные в рабочей базе: "
              + ", ".join(f"{м} ({ПИШУТ_ДАННЫЕ[м]})" for м in пропущены))
    if аргументы.все and not пропущены:
        return None, пропущены
    return отобраны, пропущены


def главная() -> int:
    разбор = argparse.ArgumentParser(
        description="Прогон модулей YAxUnit в рабочей базе (docs/yaxunit-bootstrap.md §6.1). "
                    "Код возврата: 0 - все прошли, 1 - есть красные, 2 - стенд.")
    режим = разбор.add_mutually_exclusive_group(required=True)
    режим.add_argument("--модули", nargs="+", metavar="МОДУЛЬ", help="названные тестовые модули")
    режим.add_argument("--дифф", action="store_true", help="модули объектов, затронутых веткой")
    режим.add_argument("--все", action="store_true", help="все тестовые модули тестового расширения")
    разбор.add_argument("--база-ветки",
                        help=f"с чем сравнивать для --дифф (по умолчанию origin/{ВЕТКА_РАЗРАБОТКИ})")
    разбор.add_argument("--только-отбор", action="store_true", help="напечатать отбор без прогона")
    разбор.add_argument("--без-свежести", action="store_true", help="не сверять базу с логом EDT")
    разбор.add_argument("--каталог", help="каталог результата (по умолчанию во временном)")
    разбор.add_argument("--дедлайн", type=int, help="секунд на прогон (по умолчанию из конфига)")
    аргументы = разбор.parse_args()

    проверить_настройку()
    конфиг = прочитать_конфиг()
    исходники = Path(конфиг["исходники"])
    try:
        ветка = git(исходники, "branch", "--show-current").strip() or "detached"
        print(f"Стенд: {' '.join(конфиг['подключение'])}; исходники {исходники} ({ветка})")
        модули, _ = составить_отбор(аргументы, конфиг, исходники)
        if аргументы.только_отбор:
            return КОД_ЗЕЛЕНЫЙ
        if модули is not None and not модули:
            print("ВЕРДИКТ: тестов для затронутого нет, прогона не было")
            return КОД_ЗЕЛЕНЫЙ
        if аргументы.без_свежести:
            print("Свежесть: не проверялась (--без-свежести)")
        else:
            print(f"Свежесть: {проверить_свежесть(конфиг, исходники)}")

        метка = datetime.datetime.now().strftime("%Y%m%d-%H%M%S")
        каталог = Path(аргументы.каталог or Path(tempfile.gettempdir()) / "yaxunit" / метка).resolve()
        каталог.mkdir(parents=True, exist_ok=True)
        run_json = записать_run_json(каталог, модули)
        запустить(конфиг, каталог, run_json, аргументы.дедлайн or int(конфиг["дедлайн"]))
    except ОшибкаСтенда as ошибка:
        print(f"ВЕРДИКТ: стенд - {ошибка}")
        return КОД_СТЕНД
    except OSError as ошибка:
        print(f"ВЕРДИКТ: стенд - ошибка файловой системы: {ошибка}")
        return КОД_СТЕНД

    замечания = замечания_стенда(каталог, исходники)
    try:
        итог = разобрать_отчет(каталог / "report.xml")
    except (ET.ParseError, OSError) as ошибка:
        print(f"ВЕРДИКТ: стенд - отчет не разбирается ({ошибка}): {каталог / 'report.xml'}")
        return КОД_СТЕНД
    код_движка = прочитать(каталог / "exitcode.txt")
    print(f"Итог: всего {итог['всего']}, прошло {итог['прошло']}, упало {len(итог['красные'])}, "
          f"пропущено {итог['пропущено']}; exitcode.txt: {код_движка or 'нет'}")
    for имя, сообщение in итог["красные"]:
        print(f"  КРАСНЫЙ {имя}: {сообщение}")
    print(f"Отчет: {каталог / 'report.xml'}")
    код, строка = вердикт(итог, код_движка, замечания)
    print(строка)
    return код


if __name__ == "__main__":
    sys.exit(главная())
